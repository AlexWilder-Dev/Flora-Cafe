// Generates smaller responsive copies of the photos in public/images and
// writes their intrinsic sizes to src/data/images.ts (used for width/height
// attributes so nothing shifts while images load).
import { readdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const dir = path.join(root, 'public/images')
const WIDTHS = [480, 960]
const SKIP = /^(logo-|favicon|order-)|-\d+\.webp$/

const files = (await readdir(dir)).filter((f) => f.endsWith('.webp') && !SKIP.test(f)).sort((a, b) =>
  a.localeCompare(b, 'en', { numeric: true }),
)

const meta = {}
for (const file of files) {
  const name = file.replace(/\.webp$/, '')
  const src = path.join(dir, file)
  const { width, height } = await sharp(src).metadata()
  const variants = []
  for (const w of WIDTHS) {
    if (w >= width * 0.85) continue
    await sharp(src).resize({ width: w }).webp({ quality: 74, effort: 6 }).toFile(path.join(dir, `${name}-${w}.webp`))
    variants.push(w)
  }
  meta[name] = { width, height, variants }
  console.log(`${name}: ${width}x${height} -> ${variants.join(', ') || 'no variants'}`)
}

const body = `// Generated by scripts/images.mjs. Do not edit by hand.
export const imageMeta = ${JSON.stringify(meta, null, 2)} as const satisfies Record<string, { width: number; height: number; variants: readonly number[] }>

export type ImageName = keyof typeof imageMeta
`
await writeFile(path.join(root, 'src/data/images.ts'), body)
